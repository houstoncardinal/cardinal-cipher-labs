// Build step 3 of 3 (see "build" in package.json):
//   1. vite build                 → client bundle in dist/
//   2. vite build --ssr ...       → server renderer in dist-ssr/
//   3. node scripts/prerender.mjs → static HTML for every public route + sitemap.xml
//
// Each route is written as dist/<path>.html (Netlify serves /about from about.html),
// with its own <title>, meta description, canonical, Open Graph tags and JSON-LD.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dist = path.join(root, "dist");
const SITE = "https://visitcardinal.com";

// The generated Supabase client reads localStorage when imported; give Node an inert stand-in.
const memoryStorage = { getItem: () => null, setItem() {}, removeItem() {}, clear() {}, key: () => null, length: 0 };
globalThis.localStorage ??= memoryStorage;
globalThis.sessionStorage ??= memoryStorage;

const template = fs.readFileSync(path.join(dist, "index.html"), "utf8");
const { render, publicPaths, noindexPaths, redirects, services, landingPages, caseStudies, articles, homeFaqs } = await import(
  pathToFileURL(path.join(root, "dist-ssr", "entry-server.js")).href
);

const SEO_BLOCK = /<!--seo-start-->[\s\S]*?<!--seo-end-->/;

function page(url) {
  const { html, head } = render(url);
  if (!head.includes("<title")) throw new Error("no <title> rendered");
  return template.replace(SEO_BLOCK, head).replace("<!--app-html-->", html);
}

function outFile(url) {
  return url === "/" ? path.join(dist, "index.html") : path.join(dist, `${url.replace(/^\//, "")}.html`);
}

// Un-rendered shell for client-only routes (admin) — see the generated _redirects below.
fs.writeFileSync(path.join(dist, "app.html"), template.replace("<!--app-html-->", ""));

let ok = 0;
const failed = [];
for (const url of [...new Set(publicPaths)]) {
  const file = outFile(url);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  try {
    fs.writeFileSync(file, page(url));
    ok++;
  } catch (err) {
    // Never break the deploy: fall back to the client-rendered shell for this URL.
    fs.writeFileSync(file, template.replace("<!--app-html-->", ""));
    failed.push(`${url} — ${err.message}`);
  }
}

// Real 404 page (Netlify serves dist/404.html with a 404 status for unknown URLs)
fs.writeFileSync(path.join(dist, "404.html"), page("/__404__"));

// sitemap.xml — indexable pages only
const today = new Date().toISOString().slice(0, 10);
const priority = (u) => (u === "/" ? "1.0" : /^\/services(\/|$)/.test(u) ? "0.9" : /^\/(portfolio|about|contact|pricing)/.test(u) ? "0.8" : "0.7");
const urls = [...new Set(publicPaths)]
  .filter((u) => !noindexPaths.has(u))
  .map((u) => `  <url><loc>${SITE}${u === "/" ? "/" : u}</loc><lastmod>${today}</lastmod><priority>${priority(u)}</priority></url>`);
fs.writeFileSync(
  path.join(dist, "sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join("\n")}\n</urlset>\n`,
);

// Netlify _redirects — generated from src/lib/redirects.ts so it can never drift from the app
const redirectLines = Object.entries(redirects).map(([from, to]) => `${from.padEnd(52)} ${to.padEnd(44)} 301`);
fs.writeFileSync(
  path.join(dist, "_redirects"),
  [
    "# GENERATED by scripts/prerender.mjs from src/lib/redirects.ts — edit that file, not this one.",
    "# Public pages are pre-rendered; unknown URLs fall through to /404.html with a real 404.",
    "",
    "# Pages that share a name with a folder of sub-pages",
    "/services       /services.html    200",
    "/blog           /blog.html        200",
    "/portfolio      /portfolio.html   200",
    "",
    "# Client-only admin dashboard (not pre-rendered, not indexed)",
    "/admin          /app.html         200",
    "/admin/*        /app.html         200",
    "",
    "# Permanent redirects",
    ...redirectLines,
    "/industries/*                                        /industry/:splat                             301",
    "",
  ].join("\n"),
);

// llms.txt — a plain-language summary for AI assistants and AI search engines,
// generated from the same data as the site so it is always accurate.
const priceLine = (svc) => {
  const priced = svc.tiers.filter((t) => /\d/.test(t.price));
  if (!priced.length) return "Custom quote after a free consultation";
  return svc.tiers.map((t) => `${t.name}: ${t.price}${/\d/.test(t.price) ? ` ${t.billing}` : ""}`).join("; ");
};
const llms = [
  "# Cardinal Consulting",
  "",
  "> Cardinal Consulting is a digital agency headquartered in Houston, Texas (founded 2020) that designs, builds, and grows digital businesses: web development, mobile apps, AI & automation, brand identity, UX/UI design, SEO, digital marketing, social media management, technical consulting (including fractional CTO), and website care & maintenance. It serves Houston-area businesses in person and clients across the United States remotely.",
  "",
  "## Key facts",
  "- Legal name: Cardinal Consulting LLC",
  "- Founder & CEO: Hunain Qureshi",
  "- Headquarters: 2100 West Loop S Fwy, Houston, TX 77027 (Uptown / Galleria area)",
  "- Phone: (281) 901-7016",
  "- Email: Hunain@visitcardinal.com",
  "- Website: https://visitcardinal.com",
  "- Free consultation; replies within 24 hours; written scope, timeline, and price before work begins",
  "",
  "## Services",
  ...services.map((svc) => `- [${svc.name}](${SITE}${svc.path}): ${svc.summary} Pricing — ${priceLine(svc)}.`),
  "",
  "## Industry and Houston pages",
  ...landingPages.map((p) => `- [${p.name}](${SITE}${p.path}): ${p.summary}`),
  "",
  "## Case studies",
  ...caseStudies.filter((c) => c.detail).map((c) => `- [${c.client}](${SITE}/portfolio/${c.slug}): ${c.summary}`),
  `- Full portfolio: ${SITE}/portfolio`,
  "",
  "## Guides",
  ...articles.map((a) => `- [${a.title}](${SITE}/blog/${a.slug}): ${a.excerpt}`),
  "",
  "## Frequently asked questions",
  ...homeFaqs.flatMap((f) => [`### ${f.question}`, f.answer, ""]),
  "## More",
  `- Pricing guide: ${SITE}/pricing`,
  `- About: ${SITE}/about`,
  `- Contact: ${SITE}/contact`,
  "",
].join("\n");
fs.writeFileSync(path.join(dist, "llms.txt"), llms);

fs.rmSync(path.join(root, "dist-ssr"), { recursive: true, force: true });

console.log(`prerender: ${ok} pages rendered, ${urls.length} URLs in sitemap.xml`);
if (failed.length) {
  console.warn(`prerender: ${failed.length} page(s) fell back to client rendering:\n  ${failed.join("\n  ")}`);
}
